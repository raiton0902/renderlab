#!/usr/bin/env python
"""Regenerate the embedded cell copies inside renderlab_pack.py.

Marketplace sandboxes (Agensi among them) run each script alone from a temporary
file, so `assets/cells` is not on disk. The packer therefore carries a generated
copy of every cell. Edit the cell files, then run:

    python tools/embed_cells.py
    python scripts/renderlab_pack.py --selfcheck
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
CELLS = ROOT / "assets" / "cells"
PACKER = ROOT / "scripts" / "renderlab_pack.py"

ORDER = ["00_intro.md", "01_unpack.py", "02_install.py",
         "03_smoke.py", "04_render.py", "05_deliver.py"]

BEGIN = "# --- BEGIN EMBEDDED CELLS"
END = "# --- END EMBEDDED CELLS"


def main() -> int:
    lines = [
        BEGIN + " (generated by tools/embed_cells.py - do not edit by hand)",
        "_EMBEDDED_CELLS = {",
    ]
    for name in ORDER:
        text = (CELLS / name).read_text(encoding="utf-8")
        if "'''" in text:
            raise SystemExit("%s contains triple single quotes; pick another delimiter" % name)
        lines.append("    %r: r'''%s'''," % (name, text))
    lines.append("}")
    lines.append(END)
    block = "\n".join(lines) + "\n"

    src = PACKER.read_text(encoding="utf-8")
    if BEGIN in src:
        start = src.index(BEGIN)
        stop = src.index(END, start) + len(END)
        src = (src[:start] + src[stop:]).rstrip() + "\n"
    guard = src.index('if __name__ == "__main__":')
    src = src[:guard] + block + "\n" + src[guard:]
    PACKER.write_text(src, encoding="utf-8")
    print("embedded %d cells into %s" % (len(ORDER), PACKER))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
